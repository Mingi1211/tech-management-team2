-- 이미 schema.sql 을 돌려 둔 DB 도 이 줄 하나로 따라온다 (reset 불필요).
alter table course add column if not exists professors text[] not null default '{}';


-- ── 이미 돌려 둔 DB 정리 (2026-09-20) ───────────────────────────────────────
--  로봇학실험과 AI로봇실험은 사실상 같은 과목이라 하나로 합친다.
--    로봇학실험N   → 로봇학실험/AI로봇실험N
--    AI로봇실험3   → 위 3 번으로 흡수하고 삭제
--  처음 돌리는 DB 에서는 아무 일도 하지 않는다.

update course
   set name = '로봇학실험/AI로봇실험' || substring(name from '[0-9]$')
 where dept_code = 'robot' and name ~ '^로봇학실험[1-4]$';

do $$
declare merged_id bigint;
begin
  select id into merged_id
    from course where dept_code = 'robot' and name = '로봇학실험/AI로봇실험3';

  if merged_id is not null then
    -- 흡수되는 과목을 가리키던 응답은 합쳐진 과목으로 옮긴다
    update report set course_id = merged_id
     where course_id in (select id from course
                          where dept_code = 'robot' and name = 'AI로봇실험3');
    delete from course where dept_code = 'robot' and name = 'AI로봇실험3';
  end if;
end $$;

-- 응답에 남아 있는 옛 이름도 함께 고친다 (트리거가 load_event 를 다시 만든다)
update report
   set course_name = '로봇학실험/AI로봇실험' || substring(course_name from '[0-9]$')
 where dept_code = 'robot' and course_name ~ '^(로봇학실험|AI로봇실험)[1-4]$';

