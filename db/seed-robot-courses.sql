-- 1) 학기·구분별 몇 과목인가  → 1학기 17 · 2학기 17 (AI로봇실험3 이 합쳐져 34과목)
select typical_term as 학기, course_type as 구분, count(*) as 과목수
from course where dept_code = 'robot'
group by 1, 2 order by 1, 2;

-- 2) 개설학년 × 학기 배치 — 로드맵이 읽을 표
select typical_year as 학년, typical_term as 학기,
       string_agg(name, ', ' order by name) as 과목
from course where dept_code = 'robot'
group by 1, 2 order by 1, 2;

-- 3) 아직 못 채운 칸  → 0 줄이어야 한다
--    로봇학실험은 학수번호·담당교수를 쓰지 않기로 해서 제외한다
select name, code, typical_year, professors
from course
where dept_code = 'robot'
  and name not like '로봇학실험%'
  and (code is null or cardinality(professors) = 0)
order by name;
